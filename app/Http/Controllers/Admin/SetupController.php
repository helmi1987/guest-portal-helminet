<?php

namespace App\Http\Controllers\Admin;

use App\Http\Controllers\Controller;
use App\Jobs\QueryRouterState;
use App\Models\LocalSetting;
use App\Models\NasClient;
use App\Models\Site;
use App\Nas\NasDriver;
use App\Nas\RouterOs\RouterStateDriver;
use App\Nas\RouterOs\RouterStateQuery;
use App\Support\Audit;
use App\Support\PortalAddress;
use Illuminate\Http\RedirectResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Carbon;
use Illuminate\Support\Collection;
use Illuminate\Support\Facades\Validator;
use Illuminate\Validation\Validator as ValidatorInstance;
use Illuminate\View\View;

/**
 * Setup assistant per site (admin only, CONCEPT.md §9): guided steps with the commands generated by
 * the site's NAS driver. Guest network inputs are stored in the site setting "setup" (replicated with
 * the site); the RouterOS container inputs belong to this instance (local setting).
 */
class SetupController extends Controller
{
    public const CONTAINER_KEY = 'setup_container';

    public function show(Site $site): View
    {
        $site->load('nasClients');
        $driver = $site->driver();
        $routers = $site->nasClients->sortBy('name')->values();
        $site->setRelation('nasClients', $routers);
        $container = (array) LocalSetting::get(self::CONTAINER_KEY, []);

        // Router state (CONCEPT.md §9, decision 2026-10-31): inputs derived per field from the routers
        // with a stored state, comparison per router, commands greyed out while a state is missing or
        // stale for any router with API access.
        $apiRouters = $routers->filter(fn (NasClient $nas) => $nas->hasApiAccess());
        $stateDriver = $driver instanceof RouterStateDriver ? $driver : null;
        $inputsAt = $this->inputsChangedAt($site);
        // Prefill only from successful, fresh states of the routers' current API hosts
        $sources = $stateDriver ? $apiRouters->filter(fn (NasClient $nas) => is_array($nas->router_state)
            && $this->fresh($nas, $inputsAt) && ($nas->router_state['host'] ?? null) === $nas->api_host)->values() : collect();
        $derived = $sources->isNotEmpty() ? $this->derived($driver, $site, $sources) : [];
        $view = $derived !== [] ? $site->withDerivedSetup(array_map(fn ($d) => $d[0], $derived)) : $site;
        $states = $routers->mapWithKeys(fn (NasClient $nas) => [$nas->id => [
            'fresh' => $this->fresh($nas, $inputsAt),
            'compare' => $stateDriver && is_array($nas->router_state) ? $stateDriver->compareState($view, $nas->router_state) : null,
            'version' => $nas->router_state['menus']['/system resource']['rows'][0]['version'] ?? null,
            'queued' => QueryRouterState::queuedAt((string) $nas->id),
        ]]);
        $stale = $apiRouters->contains(fn (NasClient $nas) => ! $states[$nas->id]['fresh']);

        return view('admin.sites.setup', [
            'site' => $site,
            'setup' => array_diff_key((array) $site->setting('setup', []), ['wifi_password' => true]),
            'derived' => $derived,
            'derivedFrom' => $sources->pluck('name')->intersect(array_column($derived, 2))->implode(', '),
            'wifiPasswordSet' => $site->wifiPassword() !== null,
            'wifiPasswordUnavailable' => $site->wifiPasswordUnavailable(),
            'wifiPasswordShared' => $site->wifiPasswordShared(),
            'portalAddressProblem' => PortalAddress::problem($site->setting('portal_address'), (array) $view->setting('setup', [])),
            'container' => $container,
            'commands' => $driver->setupCommands($view, $container),
            'fetch' => $routers->mapWithKeys(fn ($nas) => [$nas->id => $driver->loginPageFetch($view, $nas)]),
            'apiAccess' => $stateDriver ? $routers->mapWithKeys(fn ($nas) => [$nas->id => $driver->apiAccessCommands($view, $nas)]) : collect(),
            'states' => $states,
            'stateSupported' => $stateDriver !== null,
            'cliDisabled' => $stale,
            'maxAge' => (int) config('portal.router_api.max_age_minutes', 15),
        ]);
    }

    /** Query the state of one router (read-only API), then back to the assistant. */
    public function queryState(Site $site, NasClient $router, RouterStateQuery $query): RedirectResponse
    {
        $router->setRelation('site', $site);
        $error = $query->run($router);

        return redirect()->to(route('admin.sites.setup', $site).'#step-state')
            ->with('status', $error === null ? __('portal.router_api.queried', ['name' => $router->name]) : null);
    }

    /**
     * Queue the state query of every router of the site with API access ("Refresh"): one low-priority
     * job per router (worker of the container), the page shows the routers still queued.
     */
    public function refreshState(Site $site): RedirectResponse
    {
        foreach ($site->nasClients as $router) {
            if ($router->hasApiAccess()) {
                QueryRouterState::request($router);
            }
        }

        return redirect()->to(route('admin.sites.setup', $site).'#step-state')
            ->with('status', __('portal.router_api.refresh_queued'));
    }

    /**
     * Derived inputs that pass the driver's validation rules, only for fields without a saved value,
     * chosen per field over all source routers (sorted by name): the first router whose own object
     * (source "own") provides a valid value, else the first router providing a valid value at all
     * (enabled CAPsMAN, default profile, only bridge).
     *
     * @param  Collection<int, NasClient>  $routers
     * @return array<string, array{0: string|int, 1: string, 2: string}> field => [value, source, router name]
     */
    private function derived(NasDriver&RouterStateDriver $driver, Site $site, Collection $routers): array
    {
        $rules = $driver->setupFields()['network'];
        $out = [];
        foreach ($routers as $nas) {
            foreach ($driver->deriveSetup($site, $nas->router_state) as $field => [$value, $source]) {
                if (! isset($rules[$field]) || (isset($out[$field]) && ($out[$field][1] === 'own' || $source !== 'own'))
                    || ! Validator::make([$field => $value], [$field => $rules[$field]])->passes()) {
                    continue;
                }
                $out[$field] = [$value, $source, $nas->name];
            }
        }

        return $out;
    }

    /** Last change of the assistant's inputs: site (setup, hosts, addresses) and the container inputs. */
    private function inputsChangedAt(Site $site): ?Carbon
    {
        $container = LocalSetting::query()->find(self::CONTAINER_KEY)?->updated_at;

        return collect([$site->updated_at, $container])->filter()->max();
    }

    /** A successful state query newer than max_age_minutes, the inputs and the router's access settings. */
    private function fresh(NasClient $nas, ?Carbon $inputsAt): bool
    {
        $at = $nas->router_state_at;

        return $nas->hasApiAccess() && $at !== null && $nas->router_state_error === null
            && $at->gte(now()->subMinutes((int) config('portal.router_api.max_age_minutes', 15)))
            && ($inputsAt === null || $at->gte($inputsAt)) && ($nas->updated_at === null || $at->gte($nas->updated_at));
    }

    public function updateNetwork(Request $request, Site $site): RedirectResponse
    {
        $data = $this->validateWithin($request, $site->driver()->setupFields()['network'], 'subnet', ['gateway', 'pool']);
        $data['vlan_id'] = (int) $data['vlan_id'];
        // Guest Wi-Fi password: empty field keeps the stored one, the checkbox removes it. Shared with other
        // instances: replicated setting encrypted with the federation data key; otherwise only in the local
        // column (APP_KEY). Toggling moves the value, no copy stays in the other storage. Only the non-secret
        // flags wifi_security (wpa|open) and wifi_password_shared are replicated. Never audited or logged.
        $password = (string) ($data['wifi_password'] ?? '');
        $clear = (bool) ($data['wifi_password_clear'] ?? false);
        $shared = (bool) ($data['wifi_password_shared'] ?? false);
        unset($data['wifi_password'], $data['wifi_password_clear']);
        $plain = $clear ? null : ($password !== '' ? $password : $site->wifiPassword());
        $data['wifi_security'] = $clear ? 'open' : ($plain !== null ? 'wpa' : $site->wifiSecurity());
        $data['wifi_password_shared'] = $shared;
        $local = null;
        if ($shared) {
            $stored = $site->setting(Site::WIFI_PASSWORD);
            $cipher = $plain !== null ? Site::encryptWifiPassword($plain) : ($clear || ! is_string($stored) ? null : $stored);
            if ($cipher !== null) {
                $data['wifi_password'] = $cipher;
            }
        } else {
            $local = $plain ?? ($clear ? null : $site->wifi_password_local);
        }
        $site->forceFill(['settings' => array_merge($site->settings ?? [], ['setup' => $data]), 'wifi_password_local' => $local])->save();
        Audit::log('site.setup_network', $site, array_diff_key($data, ['wifi_password' => true]));

        return redirect()->to(route('admin.sites.setup', $site).'#step-network')->with('status', __('portal.saved'));
    }

    public function updateContainer(Request $request, Site $site): RedirectResponse
    {
        $data = $this->validateWithin($request, $site->driver()->setupFields()['container'], 'veth_address', ['veth_gateway']);
        LocalSetting::put(self::CONTAINER_KEY, $data);
        Audit::log('settings.setup_container', $site, $data);

        return redirect()->to(route('admin.sites.setup', $site).'#step-container')->with('status', __('portal.saved'));
    }

    /**
     * Validate the driver rules plus IPv4 consistency: the CIDR field must be a valid IPv4 network,
     * the other fields (addresses or "from-to" ranges) must lie inside it.
     */
    private function validateWithin(Request $request, array $rules, string $cidrField, array $inside): array
    {
        return Validator::make($request->all(), $rules)->after(function (ValidatorInstance $v) use ($request, $cidrField, $inside) {
            if ($v->errors()->hasAny([$cidrField, ...$inside])) {
                return;
            }
            [$ip, $bits] = explode('/', (string) $request->input($cidrField)) + [1 => ''];
            $base = self::ip($ip);
            if ($base === null) {
                $v->errors()->add($cidrField, __('portal.setup.invalid_ip'));

                return;
            }
            $mask = (-1 << (32 - (int) $bits)) & 0xFFFFFFFF;
            foreach ($inside as $field) {
                $parts = explode('-', (string) $request->input($field));
                $ips = array_map(self::ip(...), $parts);
                if (in_array(null, $ips, true)) {
                    $v->errors()->add($field, __('portal.setup.invalid_ip'));
                } elseif (array_filter($ips, fn ($a) => ($a & $mask) !== ($base & $mask)) !== []
                    || (count($ips) === 2 && $ips[0] > $ips[1])) {
                    $v->errors()->add($field, __('portal.setup.not_in_subnet', ['subnet' => $request->input($cidrField)]));
                }
            }
        })->validate();
    }

    /** IPv4 address as integer, null if invalid (each octet 0-255, no leading zeros). */
    private static function ip(string $value): ?int
    {
        return filter_var($value, FILTER_VALIDATE_IP, FILTER_FLAG_IPV4) ? ip2long($value) : null;
    }
}
